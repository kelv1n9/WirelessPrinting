// Sends a file to the simulated printer's card and demands that what lands there is
// byte for byte what should have landed there, damaged wire and all.

#include <cassert>
#include <cstdio>
#include <string>
#include <vector>
#include "sim/MarlinSim.h"
#include "sim/Wire.h"
#include "../ESP8266WirelessPrintAsync/CardTransfer.h"

static int failures = 0;
static const char *scenario = "";
static void check(const bool ok, const char *what) {
  if (!ok) { printf("  FAIL  %s: %s\n", scenario, what); ++failures; }
}

struct StringSource : LineSource {
  std::string text;
  size_t at = 0;
  explicit StringSource(std::string body) : text(std::move(body)) {}
  int next(char *out, const size_t max) override {
    if (at >= text.size()) return -1;
    size_t n = 0;
    while (at < text.size() && text[at] != '\n') {
      if (n + 1 < max) out[n++] = text[at];
      at++;
    }
    if (at < text.size()) at++;        // step over the newline
    out[n] = 0;
    return (int)n;
  }
  uint32_t used() const override { return (uint32_t)at; }
};

static CardTransfer *live = nullptr;
static void feedTransfer(const char *line, void *) { if (live) live->observe(line); }

// What Marlin should end up with: comments gone, blanks gone, every line closed by CRLF
static std::string expected(const std::string &source) {
  std::string out;
  size_t at = 0;
  while (at <= source.size()) {
    const size_t nl = source.find('\n', at);
    std::string line = source.substr(at, nl == std::string::npos ? std::string::npos : nl - at);
    at = nl == std::string::npos ? source.size() + 1 : nl + 1;
    std::vector<char> buf(line.begin(), line.end());
    buf.push_back(0);
    if (CardTransfer::strip(buf.data()))
      out += std::string(buf.data()) + "\r\n";
  }
  return out;
}

static std::string makeGcode(const int moves) {
  std::string body = "; generated by a slicer\r\n;FLAVOR:Marlin\r\n\r\nM104 S210\r\nM109 S210\r\nG28\r\n";
  char buf[96];
  for (int i = 0; i < moves; i++) {
    snprintf(buf, sizeof buf, "G1 X%d.%02d Y%d.%02d E%d.%04d F1800 ; a comment nobody needs\r\n",
             i % 200, i % 100, i % 150, i % 90, i / 100, i % 10000);
    body += buf;
    if (i % 50 == 0) body += "\r\n";                       // blank lines the slicer leaves
    if (i % 97 == 0) body += ";LAYER:" + std::to_string(i) + "\r\n";
  }
  body += "M104 S0\r\nM140 S0\r\nM84\r\n";
  return body;
}

struct Rig {
  MarlinSim sim;
  Wire wire;
  PrinterLink link;
  CardIndex index;
  CardTransfer move;
  Rig(const uint32_t baud = 115200, const size_t ring = 64) : wire(sim, baud) {
    sim.rxBufferSize = ring;
    link.begin(&wire);
    link.budgetBytes = (uint16_t)(ring - 8);
    link.onOther = feedTransfer;
    move.link = &link;
    move.index = &index;
    live = &move;
  }
  uint32_t pump(const uint32_t limitMs = 900000) {
    const uint32_t began = wire.clock;
    while (wire.clock - began < limitMs) {
      if (wire.clock % 3 == 0) {
        move.service(wire.clock);
        link.service();
      }
      wire.advance();
      if ((move.phase == CardDone || move.phase == CardFailed) && move.quiet())
        return wire.clock - began;
    }
    return 0;
  }
};

int main() {
  const std::string body = makeGcode(1500);
  const std::string want = expected(body);

  scenario = "a clean run puts exactly the right bytes on the card";
  {
    Rig rig;
    StringSource src(body);
    rig.move.deadManSeconds = 120;
    check(rig.move.start(&src, "PART01.GCO", body.size(), false, 0), "accepted");
    const uint32_t ms = rig.pump();
    check(ms > 0, "finished");
    check(rig.move.phase == CardDone, rig.move.trouble[0] ? rig.move.trouble : "reached done");
    check(rig.sim.card.count("PART01.GCO") == 1, "the file is on the card");
    check(rig.sim.card["PART01.GCO"] == want, "byte for byte what it should be");
    check(rig.move.written == want.size(), "our own count agrees with the card");
    printf("  %u ms, %u lines, %u skipped, %u bytes\n",
           ms, rig.move.lines, rig.move.skipped, rig.move.written);
  }

  scenario = "the dead man timer comes off and goes back on";
  {
    Rig rig;
    StringSource src("G28\r\nG1 X1\r\n");
    rig.move.deadManSeconds = 120;
    rig.move.start(&src, "TINY.GCO", 12, false, 0);
    rig.pump();
    bool off = false, back = false;
    for (const auto &cmd : rig.sim.seen) {
      if (cmd == "M85 S0") off = true;
      if (cmd == "M85 S120") back = true;
    }
    check(off, "taken off before the write");
    check(back, "put back after it");
  }

  scenario = "a damaged wire still lands the file whole";
  {
    Rig rig;
    rig.sim.corruptEvery = 1200;
    StringSource src(body);
    check(rig.move.start(&src, "PART02.GCO", body.size(), false, 0), "accepted");
    const uint32_t ms = rig.pump();
    check(ms > 0, "finished");
    check(rig.move.phase == CardDone, rig.move.trouble[0] ? rig.move.trouble : "reached done");
    check(rig.sim.card["PART02.GCO"] == want, "byte for byte what it should be");
    printf("  %u ms, %u repeats on the link, %u resyncs\n", ms, rig.link.resends, rig.link.resyncs);
  }

  scenario = "fast wire and a bigger buffer, the target setting";
  {
    Rig rig(500000, 512);
    rig.sim.lfnWrite = true;
    rig.sim.corruptEvery = 1500;
    rig.sim.stallEvery = 11; rig.sim.stallFor = 3;
    StringSource src(body);
    check(rig.move.start(&src, "a part with a long name.gcode", body.size(), false, 0), "accepted");
    const uint32_t ms = rig.pump();
    check(ms > 0, "finished");
    check(rig.move.phase == CardDone, rig.move.trouble[0] ? rig.move.trouble : "reached done");
    check(rig.sim.card["a part with a long name.gcode"] == want, "byte for byte what it should be");
    check(rig.sim.dropped == 0, "the printer lost nothing");
    printf("  %u ms for %zu bytes, %u repeats\n", ms, want.size(), rig.link.resends);
  }

  scenario = "the same thing on a clean wire, for the honest best case";
  {
    Rig rig(500000, 512);
    rig.sim.lfnWrite = true;
    StringSource src(body);
    rig.move.start(&src, "clean.gcode", body.size(), false, 0);
    const uint32_t ms = rig.pump();
    check(rig.move.phase == CardDone, rig.move.trouble[0] ? rig.move.trouble : "done");
    check(rig.sim.card["clean.gcode"] == want, "byte for byte what it should be");
    printf("  %u ms for %zu bytes, which is %.1f KB/s, so a 800 KB file in about %.0f s\n",
           ms, want.size(), want.size() / (double)ms, 800000.0 * ms / want.size() / 1000.0);
  }

  scenario = "no card in the printer is a clean refusal, not a hang";
  {
    Rig rig;
    rig.sim.cardPresent = false;
    StringSource src(body);
    rig.move.start(&src, "PART03.GCO", body.size(), false, 0);
    const uint32_t ms = rig.pump(60000);
    check(ms > 0, "it gave up instead of hanging");
    check(rig.move.phase == CardFailed, "and said so");
    printf("  gave up after %u ms: %s\n", ms, rig.move.trouble);
  }

  scenario = "stopping halfway closes the file instead of leaving it open";
  {
    Rig rig;
    StringSource src(body);
    rig.move.start(&src, "PART04.GCO", body.size(), false, 0);
    for (uint32_t i = 0; i < 400000; i++) {
      if (rig.wire.clock % 3 == 0) { rig.move.service(rig.wire.clock); rig.link.service(); }
      rig.wire.advance();
      if (rig.move.lines > 300) rig.move.stop();
      if (rig.move.phase == CardDone || rig.move.phase == CardFailed) break;
    }
    check(rig.move.phase == CardFailed, "it ended as a failure");
    bool closed = false;
    for (const auto &cmd : rig.sim.seen) if (cmd == "M29") closed = true;
    if (!closed) {
      printf("  seen was:");
      for (const auto &c : rig.sim.seen) printf(" [%s]", c.c_str());
      printf("  phase=%d trouble=%s lines=%u\n", rig.move.phase, rig.move.trouble, rig.move.lines);
    }
    check(closed, "the file on the card was closed");
    check(rig.sim.card.count("PART04.GCO") == 1, "a partial file is there, not a locked one");
  }

  scenario = "asking for the print starts it from the printer's own card";
  {
    Rig rig;
    StringSource src("G28\r\nG1 X1 Y1\r\n");
    rig.move.start(&src, "GO.GCO", 20, true, 0);
    rig.pump();
    check(rig.move.phase == CardDone, rig.move.trouble[0] ? rig.move.trouble : "done");
    bool picked = false, started = false;
    for (const auto &cmd : rig.sim.seen) {
      if (cmd == "M23 GO.GCO") picked = true;
      if (cmd == "M24") started = true;
    }
    check(picked, "the file was selected");
    check(started, "and the print was started");
  }

  scenario = "a short file on the card is caught, not reported as done";
  {
    Rig rig;
    StringSource src(body);
    rig.move.start(&src, "PART05.GCO", body.size(), false, 0);
    for (uint32_t i = 0; i < 900000; i++) {
      if (rig.wire.clock % 3 == 0) { rig.move.service(rig.wire.clock); rig.link.service(); }
      rig.wire.advance();
      // The card quietly loses the tail, which is the failure a size check exists for
      if (rig.move.phase == CardClosing && rig.sim.card["PART05.GCO"].size() > 40)
        rig.sim.card["PART05.GCO"].resize(rig.sim.card["PART05.GCO"].size() - 20);
      if (rig.move.phase == CardDone || rig.move.phase == CardFailed) break;
    }
    check(rig.move.phase == CardFailed, "the shortfall was noticed");
    printf("  said: %s\n", rig.move.trouble);
  }

  scenario = "short names come out 8.3, unique enough and never empty";
  {
    struct { const char *in, *want; } cases[] = {
      { "/Benchy boat v2.gcode",    "BENCHY_B.GCO" },
      { "part.gcode",               "PART.GCO"     },
      { "/a/b/x.y.z.gco",           "X_Y_Z.GCO"    },
      { "/....gcode",               "PRINT.GCO"    },
      { "/---.gcode",               "PRINT.GCO"    },
      { "/verylongfilename.gcode",  "VERYLONG.GCO" },
      { "/__a__.gcode",             "A.GCO"        },
      { "/Ы.gcode",                 "PRINT.GCO"    },
      { "/9.gcode",                 "9.GCO"        },
    };
    for (auto &c : cases) {
      char out[CARD_DOS_BYTES];
      cardShortName(c.in, out, sizeof out);
      check(strcmp(out, c.want) == 0, c.in);
      if (strcmp(out, c.want)) printf("    got %s, wanted %s\n", out, c.want);
      check(strlen(out) < CARD_DOS_BYTES, "it fits the slot");
    }
  }

  printf(failures ? "\n%d checks failed\n" : "\nall checks passed\n", failures);
  return failures != 0;
}
